import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { registerSecret } from './jobs.js';
import { HttpError, isoNow } from './util.js';
import { saveState } from './config.js';

const execFileP = promisify(execFile);

async function git(site, args, opts = {}) {
  try {
    const { stdout } = await execFileP('git', args, { cwd: site.path, timeout: 30000, maxBuffer: 20e6, ...opts });
    return stdout;
  } catch (e) {
    if (opts.allowFail) return null;
    throw e;
  }
}

/** Env that lets git authenticate to GitHub over HTTPS with GITHUB_TOKEN, without the token appearing in argv. */
function authEnv() {
  const t = process.env.GITHUB_TOKEN;
  if (!t) return {};
  registerSecret(t);
  const basic = Buffer.from(`x-access-token:${t}`).toString('base64');
  registerSecret(basic);
  return {
    GIT_TERMINAL_PROMPT: '0',
    GIT_CONFIG_COUNT: '1',
    GIT_CONFIG_KEY_0: 'http.https://github.com/.extraheader',
    GIT_CONFIG_VALUE_0: `AUTHORIZATION: basic ${basic}`,
  };
}

function identityArgs(site) {
  const a = site.git.author || {};
  return [
    ...(a.name ? ['-c', `user.name=${a.name}`] : []),
    ...(a.email ? ['-c', `user.email=${a.email}`] : []),
  ];
}

export async function status(site) {
  const isRepo = fs.existsSync(path.join(site.path, '.git'));
  if (!isRepo) return { isRepo: false };
  const branch = (await git(site, ['rev-parse', '--abbrev-ref', 'HEAD'], { allowFail: true }))?.trim() || null;
  const remoteUrl = (await git(site, ['remote', 'get-url', site.git.remote], { allowFail: true }))?.trim() || null;
  const porcelain = (await git(site, ['status', '--porcelain=v1', '-uall'])) || '';
  const changes = porcelain.split('\n').filter(Boolean).map((l) => ({ code: l.slice(0, 2), path: l.slice(3) }));
  const log = (await git(site, ['log', '-8', '--pretty=format:%h%x09%cI%x09%s'], { allowFail: true })) || '';
  const commits = log.split('\n').filter(Boolean).map((l) => {
    const [hash, date, subject] = l.split('\t');
    return { hash, date, subject };
  });
  let ahead = null;
  let behind = null;
  const counts = await git(site, ['rev-list', '--left-right', '--count', `${site.git.remote}/${branch}...HEAD`], { allowFail: true });
  if (counts) [behind, ahead] = counts.trim().split(/\s+/).map(Number);
  return { isRepo, branch, remote: site.git.remote, remoteUrl, changes, commits, ahead, behind };
}

const LARGE = 95 * 1024 * 1024;

export async function backup(job, site, { message } = {}) {
  if (!fs.existsSync(path.join(site.path, '.git'))) {
    throw new HttpError(409, 'This site is not a git repository yet. Use "Connect to GitHub" first.');
  }
  const env = authEnv();
  await job.exec('git', ['add', '-A'], { cwd: site.path });
  const staged = (await job.exec('git', ['diff', '--cached', '--name-only', '-z'], { cwd: site.path, quiet: true })).stdout
    .split('\0').filter(Boolean);
  const tooBig = staged.filter((f) => {
    const p = path.join(site.path, f);
    return fs.existsSync(p) && fs.statSync(p).size > LARGE;
  });
  if (tooBig.length) {
    await job.exec('git', ['reset', '-q'], { cwd: site.path });
    for (const f of tooBig) job.log(`  ${f}: ${(fs.statSync(path.join(site.path, f)).size / 1048576).toFixed(0)} MB`, 'err');
    throw new Error(`${tooBig.join(', ')} ${tooBig.length > 1 ? 'are' : 'is'} larger than GitHub's 100 MB limit; add to .gitignore or shrink before backing up`);
  }
  if (staged.length) {
    job.log(`${staged.length} changed file(s)`);
    const msg = message?.trim() || `Site backup ${new Date().toISOString().replace('T', ' ').slice(0, 16)} UTC (${staged.length} files)`;
    await job.exec('git', [...identityArgs(site), 'commit', '-q', '-m', msg], { cwd: site.path });
  } else {
    job.log('no local changes to commit; pushing any unpushed commits');
  }
  const branch = (await job.exec('git', ['rev-parse', '--abbrev-ref', 'HEAD'], { cwd: site.path, quiet: true })).stdout.trim();
  const target = site.git.branch || branch;
  await job.exec('git', ['push', '-u', site.git.remote, `HEAD:refs/heads/${target}`], { cwd: site.path, env });
  await saveState((st) => {
    st.sites ??= {};
    st.sites[site.id] = { ...(st.sites[site.id] || {}), lastBackup: isoNow() };
  });
  return { committed: staged.length, branch: target };
}

export async function pull(job, site) {
  await job.exec('git', ['pull', '--ff-only', site.git.remote, site.git.branch], { cwd: site.path, env: authEnv() });
}

const DEFAULT_GITIGNORE = `# Generated by Hugo / tooling
public/
resources/_gen/
node_modules/
.hugo_build.lock
# OS noise
.DS_Store
Thumbs.db
`;

async function createGithubRepo(job, name, isPrivate) {
  const token = process.env.GITHUB_TOKEN;
  if (token) {
    const r = await fetch('https://api.github.com/user/repos', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json',
        'User-Agent': 'hugo-site-manager', 'Content-Type': 'application/json',
      },
      body: JSON.stringify({ name, private: isPrivate, auto_init: false }),
    });
    const body = await r.json();
    if (!r.ok) throw new Error(`GitHub: ${body.message || r.status}${body.errors ? ` (${body.errors.map((e) => e.message).join('; ')})` : ''}`);
    job.log(`created ${body.html_url}`);
    return body.clone_url;
  }
  // Fall back to the gh CLI's stored login.
  const { stdout } = await job.exec('gh', ['api', 'user/repos', '-f', `name=${name}`, '-F', `private=${isPrivate}`, '--jq', '.ssh_url + " " + .html_url']);
  const [sshUrl, htmlUrl] = stdout.trim().split(' ');
  job.log(`created ${htmlUrl}`);
  return sshUrl;
}

/** Turn a site folder into a git repo backed by a (new or existing) GitHub repo. */
export async function connect(job, site, { remoteUrl, createRepo, isPrivate = true }) {
  const cwd = site.path;
  if (!fs.existsSync(path.join(cwd, '.git'))) {
    await job.exec('git', ['init', '-q', '-b', site.git.branch || 'main'], { cwd });
  }
  const gi = path.join(cwd, '.gitignore');
  if (!fs.existsSync(gi)) {
    await fsp.writeFile(gi, DEFAULT_GITIGNORE);
    job.log('wrote a .gitignore that excludes public/, resources/_gen/, node_modules/ and .DS_Store');
  }
  let url = remoteUrl?.trim();
  if (!url && createRepo) {
    if (!/^[A-Za-z0-9._-]+$/.test(createRepo)) throw new HttpError(400, 'repository name may only contain letters, digits, . _ -');
    url = await createGithubRepo(job, createRepo, isPrivate);
  }
  if (!url) throw new HttpError(400, 'give either an existing remote URL or a new repository name');
  const existing = (await job.exec('git', ['remote'], { cwd, quiet: true })).stdout.split('\n');
  if (existing.includes(site.git.remote)) await job.exec('git', ['remote', 'set-url', site.git.remote, url], { cwd });
  else await job.exec('git', ['remote', 'add', site.git.remote, url], { cwd });
  return { remoteUrl: url };
}

/** Container mode: clone a site from git.cloneUrl if its folder doesn't exist yet. */
export async function ensureCloned(site, log = console.log) {
  if (fs.existsSync(site.path) || !site.git.cloneUrl) return false;
  await fsp.mkdir(path.dirname(site.path), { recursive: true });
  log(`cloning ${site.git.cloneUrl} into ${site.path}`);
  await execFileP('git', ['clone', '--branch', site.git.branch, site.git.cloneUrl, site.path], {
    env: { ...process.env, ...authEnv() }, timeout: 10 * 60e3, maxBuffer: 50e6,
  });
  return true;
}
